from datetime import datetime, timezone
from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field


class AgentMetadataResponse(BaseModel):
    """Metadata describing a registered workplace intelligence agent."""

    agent_id: str
    name: str
    description: str
    capabilities: List[str]
    is_active: bool = True


class BaseAgentInput(BaseModel):
    """Base input schema provided to every agent."""

    target_id: str = Field(..., description="Target employee, team, or workspace identifier")
    event_ids: List[str] = Field(default_factory=list, description="Associated event IDs for this analysis")
    context: Dict[str, Any] = Field(default_factory=dict, description="Contextual parameters or configurations")


class BaseAgentOutput(BaseModel):
    """Base output schema generated by every agent."""

    agent_id: str
    target_id: str
    score: float | None = Field(..., ge=0.0, le=1.0, description="Normalized score, or null when evidence is insufficient/invalid")
    rationale: str = Field(..., description="Explanation or reasoning for the evaluation")
    findings: List[str] = Field(default_factory=list, description="Actionable findings or insights")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Agent-specific details")
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


# --- 1. Workplace Architect Agent ---
class WorkplaceArchitectInput(BaseAgentInput):
    department_filter: Optional[str] = None
    target_capacity: Optional[int] = None


class WorkplaceArchitectOutput(BaseAgentOutput):
    agent_id: str = "workplace_architect"
    recommended_zones: List[str] = Field(default_factory=list)
    space_utilization_ratio: float = 0.0


# --- 2. Workplace Configuration Agent ---
class WorkplaceConfigurationInput(BaseAgentInput):
    current_layout: Dict[str, Any] = Field(default_factory=dict)
    rules_applied: List[str] = Field(default_factory=list)


class WorkplaceConfigurationOutput(BaseAgentOutput):
    agent_id: str = "workplace_configuration"
    configuration_diff: Dict[str, Any] = Field(default_factory=dict)
    compliance_score: float = 1.0


# --- 3. Contribution Agent ---
class ContributionAgentInput(BaseAgentInput):
    timeframe_days: int = 7
    activity_metrics: Dict[str, int] = Field(default_factory=dict)


class ContributionAgentOutput(BaseAgentOutput):
    agent_id: str = "contribution"
    score: float | None = Field(default=None, ge=0.0, le=1.0)
    evaluation_status: Literal["evaluated", "insufficient_evidence", "invalid_evidence"] = "insufficient_evidence"
    dimensions_used: List[Dict[str, Any]] = Field(default_factory=list)
    dimensions_missing: List[str] = Field(default_factory=list)
    dimensions_partial: List[Dict[str, Any]] = Field(default_factory=list)
    evidence_validation_status: str = "missing"
    validation_errors: List[str] = Field(default_factory=list)
    evidence_references: List[Dict[str, Any]] = Field(default_factory=list)
    confidence: float = Field(default=0.0, ge=0.0, le=1.0)
    confidence_assessment: Dict[str, Any] = Field(default_factory=dict)
    impact_level: str = "standard"  # e.g., low, standard, high, standout
    primary_contributions: List[str] = Field(default_factory=list)


# --- 4. Fairness Agent ---
class FairnessAgentInput(BaseAgentInput):
    peer_group_ids: List[str] = Field(default_factory=list)
    workload_distribution: Dict[str, float] = Field(default_factory=dict)


class FairnessAgentOutput(BaseAgentOutput):
    agent_id: str = "fairness"
    disparity_detected: bool = False
    fairness_index: float = 1.0


# --- 5. Culture Agent ---
class CultureAgentInput(BaseAgentInput):
    sentiment_indicators: Dict[str, float] = Field(default_factory=dict)
    collaboration_edges_count: int = 0


class CultureAgentOutput(BaseAgentOutput):
    agent_id: str = "culture"
    vibe_descriptor: str = "neutral"
    collaboration_health: float = 0.5


# --- 6. Environment Agent ---
class EnvironmentAgentInput(BaseAgentInput):
    noise_level_db: Optional[float] = None
    temperature_celsius: Optional[float] = None
    lighting_lux: Optional[float] = None


class EnvironmentAgentOutput(BaseAgentOutput):
    agent_id: str = "environment"
    comfort_index: float = 0.8
    anomalies: List[str] = Field(default_factory=list)


# --- 7. Reward Agent ---
class RewardAgentInput(BaseAgentInput):
    recent_recognitions: List[str] = Field(default_factory=list)
    milestones_achieved: List[str] = Field(default_factory=list)


class RewardAgentOutput(BaseAgentOutput):
    agent_id: str = "reward"
    recommended_tokens: int = 0
    kudos_message: str = ""


# --- 8. Accountability Agent ---
class AccountabilityAgentInput(BaseAgentInput):
    commitments_tracked: List[str] = Field(default_factory=list)
    sla_deadlines_met: int = 0
    sla_deadlines_missed: int = 0


class AccountabilityAgentOutput(BaseAgentOutput):
    agent_id: str = "accountability"
    reliability_index: float = 1.0
    pending_followups: List[str] = Field(default_factory=list)


# --- Route Execution Contracts ---
class AgentEvaluationRequest(BaseModel):
    """Direct request to evaluate a target using a specific agent."""

    target_id: str
    context: Dict[str, Any] = Field(default_factory=dict)


class OrchestrationRunRequest(BaseModel):
    """Request to execute the full LangGraph multi-agent pipeline."""

    target_id: str
    event_ids: List[str] = Field(default_factory=list)
    parameters: Dict[str, Any] = Field(default_factory=dict)


class OrchestrationRunResponse(BaseModel):
    """Response containing outputs of the executed multi-agent graph."""

    run_id: str
    target_id: str
    status: str = "completed"
    agent_results: Dict[str, BaseAgentOutput]
    overall_score: float | None
    summary: str
