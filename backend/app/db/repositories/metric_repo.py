from typing import List
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.future import select

from backend.app.db.models.metric import AgentEvaluation
from backend.app.db.repositories.base import BaseRepository


class MetricRepository(BaseRepository[AgentEvaluation]):
    """Repository handling AgentEvaluation persistence and intelligence metrics querying."""

    def __init__(self, session: AsyncSession) -> None:
        super().__init__(AgentEvaluation, session)

    async def get_by_target(self, target_id: str, limit: int = 50) -> List[AgentEvaluation]:
        """Fetch evaluations for a target employee or department."""
        result = await self.session.execute(
            select(AgentEvaluation)
            .filter(AgentEvaluation.target_id == target_id)
            .order_by(AgentEvaluation.created_at.desc())
            .limit(limit)
        )
        return list(result.scalars().all())

    async def get_by_agent(self, agent_id: str, limit: int = 50) -> List[AgentEvaluation]:
        """Fetch evaluations generated by a specific agent."""
        result = await self.session.execute(
            select(AgentEvaluation)
            .filter(AgentEvaluation.agent_id == agent_id)
            .order_by(AgentEvaluation.created_at.desc())
            .limit(limit)
        )
        return list(result.scalars().all())
